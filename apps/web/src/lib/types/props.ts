/**
 * Общие части props компонентов: подключаются через `interface Props extends …`.
 * Сюда — только то, что одинаково у нескольких компонентов; props одного компонента
 * объявляются в нём самом (`interface Props` в `<script>`).
 */

/** Компонент принимает `class` снаружи и объединяет его с базовыми через `mergeClasses()`. */
export interface ClassProp {
	/** Дополнить или переопределить базовые стили: при конфликте побеждает переданный класс. */
	class?: string;
}
