-- Изменено вручную (только данные, схема не меняется): название счётчика ограничено 30 символами
-- (`COUNTER_TITLE_MAX`); более длинные старые названия обрезаем, иначе настройки таких счётчиков
-- не сохранить без правки названия. rtrim — чтобы не оставить пробел на конце.
UPDATE "Counter" SET "title" = rtrim(left("title", 30)) WHERE char_length("title") > 30;
