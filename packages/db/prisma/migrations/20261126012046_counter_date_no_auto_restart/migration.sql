-- Изменено вручную (только данные, схема не меняется): у таймера «до даты» автоповтора больше нет —
-- схема ввода сбрасывает `autoRestart`, а у уже созданных счётчиков снимаем его здесь, иначе
-- воркер продолжал бы их автоматически до следующего сохранения настроек.
UPDATE "Counter" SET "autoRestart" = false WHERE "timerMode" = 'DATE';
